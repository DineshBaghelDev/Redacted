const aiStageNames = stages.filter((s) => s.kind === "llm").map((s) => s.name);

/** Drafts and AI call logs for some jobs, trimmed to what the stats need. */
async function statsInputs(ctx: QueryCtx, jobs: Doc<"generationJobs">[]) {
  const drafts = [];
  const logs = [];
  for (const job of jobs) {
    const jobDrafts = await ctx.db.query("generationDrafts").withIndex("by_job_stage", (q) => q.eq("jobId", job._id)).collect();
    drafts.push(...jobDrafts.map((d) => ({ jobId: d.jobId as string, stage: d.stage, checkErrors: d.checkErrors })));
    const jobLogs = await ctx.db.query("generationLogs").withIndex("by_job", (q) => q.eq("jobId", job._id)).collect();
    logs.push(
      ...jobLogs.map((l) => ({
        jobId: l.jobId as string,
        stage: l.stage,
        attempt: l.attempt,
        ms: l.ms,
        inputTokens: l.inputTokens,
        outputTokens: l.outputTokens,
        problems: l.problems,
        error: l.error,
      })),
    );
  }
  return { drafts, logs };
}

/** One test run's results: each case, and each AI stage across the cases. */
export const batchStats = query({
  args: { batch: v.string() },
  handler: async (ctx, { batch }) => {
    await requireDevUser(ctx);
    const jobs = await ctx.db.query("generationJobs").withIndex("by_batch", (q) => q.eq("batch", batch)).collect();
    const { drafts, logs } = await statsInputs(ctx, jobs);
    const statsJobs = jobs.map((j) => ({
      id: j._id as string,
      difficulty: j.difficulty,
      seed: j.seed,
      status: j.status,
      failedStage: j.failedStage,
      error: j.error,
      startedAt: j.startedAt,
      finishedAt: j.finishedAt,
    }));
    return { jobs: jobSummaries(statsJobs, logs), stages: stageStats(aiStageNames, drafts, logs) };
  },
});

/** How many past cases a prediction averages over. */
const HISTORY = 5;

/** Predicted AI minutes left for a job, from the last few passed cases of the same difficulty. */
export const predictTime = query({
  args: { jobId: v.id("generationJobs") },
  handler: async (ctx, { jobId }) => {
    await requireDevUser(ctx);
    const job = await ctx.db.get(jobId);
    if (!job || job.status === "passed" || job.status === "failed" || job.status === "stopped") return null;
    const recent = await ctx.db.query("generationJobs").order("desc").take(200);
    const history = recent.filter((j) => j.status === "passed" && j.difficulty === job.difficulty).slice(0, HISTORY);
    if (history.length === 0) return null;
    const { drafts, logs } = await statsInputs(ctx, history);
    const done = await ctx.db.query("generationDrafts").withIndex("by_job_stage", (q) => q.eq("jobId", jobId)).collect();
    const left = aiStageNames.filter((name) => job.running?.stage === name || !done.some((d) => d.stage === name));
    const minutesLeft = predictMinutesLeft(left, stageStats(aiStageNames, drafts, logs));
    return minutesLeft === undefined ? null : { minutesLeft, basedOn: history.length };
  },
});
