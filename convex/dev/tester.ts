/**
 * Runs one stage on the job's existing drafts (or loads its hand-written output) and saves the result
 * as that stage's draft. AI stages run in the background (see aiAttempt); the page follows along live.
 */
export const runStage = action({
  args: { jobId: v.id("generationJobs"), stage: v.string(), handWritten: v.optional(v.boolean()) },
  handler: async (ctx, { jobId, stage: stageName, handWritten }): Promise<string[]> => {
    await requireDevUser(ctx);
    const stage = getStage(stageName);
    const { job, drafts } = await ctx.runQuery(internal.generation.jobs.loadInputs, { jobId, stages: stage.inputs });
    const missing = stage.inputs.filter((name) => !(name in drafts));
    if (missing.length > 0) throw new Error(`Run these stages first: ${missing.join(", ")}`);
    if (job.running) throw new Error(`The AI is still working on "${job.running.stage}".`);
    if (job.status === "queued" || job.status === "running") throw new Error("This case is being generated by Run all. Stop it first.");

    if (handWritten) {
      if (stage.handWritten === undefined) throw new Error("This stage has no hand-written version.");
      const checkErrors = checkOutput(stage, stage.handWritten, drafts, { seed: job.seed, difficulty: job.difficulty }, false);
      await ctx.runMutation(internal.generation.jobs.saveDraft, { jobId, stage: stage.name, output: stage.handWritten, checkErrors, source: "hand-written" });
      return checkErrors;
    }
    if (stage.run) return await runCodeStage(ctx, jobId, stage.name);
    if (!stage.prompt) throw new Error("The AI version of this stage isn't built yet. Use the hand-written one.");
    await ctx.runMutation(internal.generation.jobs.setRunning, { jobId, running: { stage: stage.name, attempt: 0 } });
    await ctx.scheduler.runAfter(0, internal.dev.tester.aiAttempt, { jobId, stage: stage.name, attempt: 0 });
    return [];
  },
});

/** Reruns an AI stage's checks on its saved output (useful after the checks change). */
export const recheckStage = action({
  args: { jobId: v.id("generationJobs"), stage: v.string() },
  handler: async (ctx, { jobId, stage: stageName }): Promise<string[]> => {
    await requireDevUser(ctx);
    const stage = getStage(stageName);
    const { job, drafts, previous } = await ctx.runQuery(internal.generation.jobs.loadInputs, { jobId, stages: stage.inputs, previousOf: stage.name });
    if (!previous) throw new Error("Nothing saved for this stage yet.");
    const checkErrors = checkOutput(stage, previous.output, drafts, { seed: job.seed, difficulty: job.difficulty }, previous.source === "llm");
    await ctx.runMutation(internal.generation.jobs.saveDraft, { jobId, stage: stage.name, output: previous.output, checkErrors, source: previous.source });
    return checkErrors;
  },
});

/**
 * One AI try at a stage. Each try is its own action so a slow model can't hit the action time limit.
 * If the checks fail and repairs are left, it schedules the next try with the problems.
 */
export const aiAttempt = internalAction({
  args: { jobId: v.id("generationJobs"), stage: v.string(), attempt: v.number() },
  handler: async (ctx, { jobId, stage, attempt }) => {
    try {
      const result = await runAiTry(ctx, jobId, stage, attempt);
      if (!result.error && result.retry) {
        await ctx.runMutation(internal.generation.jobs.setRunning, { jobId, running: { stage, attempt: attempt + 1 } });
        await ctx.scheduler.runAfter(0, internal.dev.tester.aiAttempt, { jobId, stage, attempt: attempt + 1 });
        return;
      }
    } catch (error) {
      await ctx.runMutation(internal.generation.jobs.setRunning, { jobId });
      throw error;
    }
    await ctx.runMutation(internal.generation.jobs.setRunning, { jobId });
  },
});

