/**
 * Record and replay: a job's AI-written stage outputs, to save under convex/fixtures/recorded/ as a
 * permanent test case. Run with: npx convex run dev/tester:exportJob '{"jobId":"..."}'
 */
export const exportJob = internalQuery({
  args: { jobId: v.id("generationJobs") },
  handler: async (ctx, { jobId }) => {
    const job = await ctx.db.get(jobId);
    if (!job) throw new Error("Job not found.");
    const drafts = await ctx.db
      .query("generationDrafts")
      .withIndex("by_job_stage", (q) => q.eq("jobId", jobId))
      .collect();
    const outputs: Record<string, { output: unknown; source: string }> = {};
    for (const d of drafts) if (d.source !== "code") outputs[d.stage] = { output: d.output, source: d.source };
    return { jobId, seed: job.seed, difficulty: job.difficulty, outputs };
  },
});

/** Generates the whole case in the background: every stage in order, with repairs. */
export const runAll = mutation({
  args: { jobId: v.id("generationJobs") },
  handler: async (ctx, { jobId }) => {
    await requireDevUser(ctx);
    const job = await ctx.db.get(jobId);
    if (!job) throw new Error("Job not found.");
    if (job.running || job.status === "queued" || job.status === "running") throw new Error("This case is already being generated.");
    const workflowId = await workflow.start(ctx, internal.generation.workflow.generateCase, { jobId });
    await ctx.db.patch(jobId, { status: "queued", workflowId, failedStage: undefined, error: undefined, startedAt: undefined, finishedAt: undefined });
  },
});

/** A test run's difficulty mix. */
const TEST_MIX = ["easy", "normal", "hard"] as const;

/** Starts a test run: 3 new cases (one per difficulty) with random seeds, generated one after another. */
export const runTestBatch = mutation({
  args: {},
  handler: async (ctx) => {
    const createdBy = await requireDevUser(ctx);
    const batch = `Test run ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC`;
    const jobIds: Id<"generationJobs">[] = [];
    for (const level of TEST_MIX) {
      const seed = Math.floor(Math.random() * 2 ** 31);
      jobIds.push(await ctx.db.insert("generationJobs", { seed, difficulty: level, createdBy, createdAt: Date.now(), status: "queued", batch }));
    }
    const workflowId = await workflow.start(ctx, internal.generation.workflow.generateBatch, { jobIds });
    for (const jobId of jobIds) await ctx.db.patch(jobId, { workflowId });
    return batch;
  },
});

/** Stops a Run all or a whole test run; finished cases keep their result. */
export const stopRun = mutation({
  args: { jobId: v.id("generationJobs") },
  handler: async (ctx, { jobId }) => {
    await requireDevUser(ctx);
    const job = await ctx.db.get(jobId);
    if (!job?.workflowId) throw new Error("This case isn't being generated.");
    await workflow.cancel(ctx, job.workflowId as Parameters<typeof workflow.cancel>[1]);
    const jobs = job.batch ? await ctx.db.query("generationJobs").withIndex("by_batch", (q) => q.eq("batch", job.batch)).collect() : [job];
    for (const j of jobs) {
      if (j.status === "queued" || j.status === "running") await ctx.db.patch(j._id, { status: "stopped", running: undefined, finishedAt: Date.now() });
    }
  },
});

